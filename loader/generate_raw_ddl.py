"""
Generates sql/070_raw_tables.sql from loader/contracts/*.json.
Raw tables mirror the source file exactly: every column TEXT, plus lineage.
Run:  python -m loader.generate_raw_ddl
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parent / "sql" / "070_raw_tables.sql"


def load_contracts() -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((HERE / "contracts").glob("*.json"))]


def ddl_for(c: dict) -> str:
    table = f"raw.{c['source_name'].lower()}"
    pivot = c["layout"] == "STOCK_PIVOT"
    lines = ["    batch_id           BIGINT  NOT NULL REFERENCES meta.load_batch (batch_id)",
             "    source_row_number  INTEGER NOT NULL"]
    if pivot:
        lines.append("    source_col_number  INTEGER NOT NULL")
    for col in c["columns"]:
        lines.append(f"    {col['column']:<40s} TEXT")
    key = "batch_id, source_row_number, source_col_number" if pivot else "batch_id, source_row_number"
    lines.append(f"    PRIMARY KEY ({key})")
    status = "" if c["status"] == "verified" else "  -- DRAFT contract: verify on first real file"
    comments = [f"COMMENT ON COLUMN {table}.{col['column']} IS {sql_str('Source header: ' + col['header'])};"
                for col in c["columns"]]
    return (f"-- {c['source_name']}{status}\nCREATE TABLE {table} (\n" + ",\n".join(lines) + "\n);\n"
            + f"COMMENT ON TABLE {table} IS {sql_str('As received from ' + c['source_name'] + '. Contract: loader/contracts/' + c['source_name'] + '.json')};\n"
            + "\n".join(comments) + "\n")


def sql_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> None:
    parts = ["-- =============================================================================",
             "-- 070_raw_tables.sql  |  GENERATED by loader/generate_raw_ddl.py - do not edit by hand.",
             "-- Raw landing tables: one per source, every source column TEXT, append-only.",
             "-- A new export layout = new contract + regenerated file + review, never an ad-hoc ALTER.",
             "-- =============================================================================", "",
             "COMMENT ON COLUMN meta.load_batch.period_start IS 'Earliest business date present in the file (raw keeps every row)';",
             "COMMENT ON COLUMN meta.load_batch.period_end   IS 'Latest business date present in the file. The 15-Sep cut-off is applied in staging, not here';",
             "COMMENT ON COLUMN meta.load_batch.as_of_date   IS 'For snapshot / state / master files: the date the export represents (given by the operator, cross-checked with the file where it states one)';",
             ""]
    for c in load_contracts():
        parts.append(ddl_for(c))
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")   # LF on Windows too
    print(f"wrote {OUT} ({len(load_contracts())} raw tables)")


if __name__ == "__main__":
    main()
