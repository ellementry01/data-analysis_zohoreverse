-- 085_core_v2.sql  |  Migration (schema v2.0, part 2 of 3)
-- Core reshaped to the business-first design (Target Data Model v2).
-- v1 core tables held no data; they are replaced. core.dim_date is kept.
-- Conventions (unchanged): key -1 = Unknown member, natural keys UNIQUE,
-- quantities positive except the signed stock ledger, no business flags on
-- facts, no customer personal data, lineage on every fact row.
-- Every column carries a business definition (COMMENT) -> meta.column_dictionary.
-- =============================================================================

