-- =============================================================================
-- 030_core_dimensions.sql  |  Conformed dimensions
--
-- Conventions
--   * Surrogate integer keys. Natural keys kept and UNIQUE.
--   * Key -1 = "Unknown" member. Facts never hold NULL for a mandatory
--     dimension; an unmatched value maps to -1 and is counted by a DQ check,
--     so nothing is dropped silently and every total still reconciles.
--   * Dimensions are rebuilt from stg + ref; classification changes in ref
--     flow to every historical fact automatically through the join.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Date (Indian fiscal year April-March)
-- ---------------------------------------------------------------------------
CREATE TABLE core.dim_date (
    date_key            INTEGER     PRIMARY KEY,          -- YYYYMMDD
    calendar_date       DATE        NOT NULL UNIQUE,
    day_of_month        SMALLINT    NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    day_of_week_iso     SMALLINT    NOT NULL CHECK (day_of_week_iso BETWEEN 1 AND 7),  -- 1 = Monday
    day_name            VARCHAR(9)  NOT NULL,
    is_weekend          BOOLEAN     NOT NULL,
    iso_year            SMALLINT    NOT NULL,
    iso_week            SMALLINT    NOT NULL CHECK (iso_week BETWEEN 1 AND 53),
    week_start_date     DATE        NOT NULL,             -- Monday of the ISO week
    calendar_month      SMALLINT    NOT NULL CHECK (calendar_month BETWEEN 1 AND 12),
    month_name          VARCHAR(9)  NOT NULL,
    month_start_date    DATE        NOT NULL,
    is_month_end        BOOLEAN     NOT NULL,
    calendar_quarter    SMALLINT    NOT NULL CHECK (calendar_quarter BETWEEN 1 AND 4),
    calendar_year       SMALLINT    NOT NULL,
    fiscal_year_start   SMALLINT    NOT NULL,             -- 2026 for FY 2026-27
    fiscal_year_label   CHAR(7)     NOT NULL,             -- '2026-27' (matches ERP doc suffix 26-27)
    fiscal_quarter      SMALLINT    NOT NULL CHECK (fiscal_quarter BETWEEN 1 AND 4),  -- Q1 = Apr-Jun
    fiscal_month        SMALLINT    NOT NULL CHECK (fiscal_month BETWEEN 1 AND 12)    -- April = 1
);

-- ---------------------------------------------------------------------------
-- Product (every item code that appears anywhere: trading SKUs, packaging,
-- carry bags, charge lines such as SHIPPING R)
-- ---------------------------------------------------------------------------
CREATE TABLE core.dim_product (
    product_key        INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_code           VARCHAR(40)  NOT NULL UNIQUE,     -- ERP PRODNUM after TRIM
    product_name       VARCHAR(300) NOT NULL,
    item_type          VARCHAR(20)  NOT NULL CHECK (item_type IN
                          ('TRADING','PACKAGING','ACCESSORY','STORES_CONSUMABLES','SERVICE','CHARGE','UNKNOWN')),
    category           VARCHAR(100),
    sub_category       VARCHAR(100),
    product_family     VARCHAR(100),
    hsn_code           VARCHAR(10),
    uom                VARCHAR(20),
    ean_code           VARCHAR(20),                      -- from Blinkit UPC where available
    lifecycle_status   VARCHAR(15)  NOT NULL CHECK (lifecycle_status IN
                          ('CONTINUED','DISCONTINUED','NOT_IN_MASTER','NOT_APPLICABLE')),
                          -- NOT_APPLICABLE = non-trading item; NOT_IN_MASTER = trading SKU missing from master (DQ WARN)
    current_mrp        NUMERIC(12,2) CHECK (current_mrp >= 0),
    first_seen_date    DATE,
    is_unknown_member  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_dim_product_lifecycle CHECK (
        (item_type = 'TRADING' AND lifecycle_status IN ('CONTINUED','DISCONTINUED','NOT_IN_MASTER'))
     OR (item_type <> 'TRADING' AND lifecycle_status = 'NOT_APPLICABLE'))
);

-- Type-2 history of the attributes that change over time and matter for
-- analysis (lifecycle status, MRP). History starts from the first master
-- load; earlier changes cannot be reconstructed.
CREATE TABLE core.dim_product_history (
    product_history_id  BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_key         INTEGER      NOT NULL REFERENCES core.dim_product (product_key),
    lifecycle_status    VARCHAR(15)  NOT NULL,
    mrp                 NUMERIC(12,2) CHECK (mrp >= 0),
    valid_from          DATE         NOT NULL,
    valid_to            DATE,                               -- NULL = current version
    is_current          BOOLEAN      NOT NULL,
    batch_id            BIGINT       NOT NULL REFERENCES meta.load_batch (batch_id),
    CONSTRAINT uq_dim_product_history UNIQUE (product_key, valid_from),
    CONSTRAINT ck_dim_product_history_range   CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT ck_dim_product_history_current CHECK (is_current = (valid_to IS NULL))
);

-- [PG-ONLY] at most one current version per product
CREATE UNIQUE INDEX uq_dim_product_history_current
    ON core.dim_product_history (product_key) WHERE is_current;

-- ---------------------------------------------------------------------------
-- Location (built from ref.location_master)
-- ---------------------------------------------------------------------------
CREATE TABLE core.dim_location (
    location_key                SMALLINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_code               VARCHAR(40)  NOT NULL UNIQUE,
    erp_location_name           VARCHAR(100),
    location_name               VARCHAR(100) NOT NULL,
    location_type               VARCHAR(30)  NOT NULL,
    operated_by                 VARCHAR(20)  NOT NULL,
    gst_state_code              CHAR(2),
    state_name                  VARCHAR(60),
    city                        VARCHAR(60),
    is_stock_holding            BOOLEAN      NOT NULL,
    is_sellable_stock           BOOLEAN      NOT NULL,
    inventory_system_of_record  VARCHAR(20)  NOT NULL,
    is_active                   BOOLEAN      NOT NULL,
    is_confirmed                BOOLEAN      NOT NULL,
    is_unknown_member           BOOLEAN      NOT NULL DEFAULT FALSE
);

-- ---------------------------------------------------------------------------
-- Channel (built from ref.channel_master)
-- ---------------------------------------------------------------------------
CREATE TABLE core.dim_channel (
    channel_key        SMALLINT     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_code       VARCHAR(40)  NOT NULL UNIQUE,
    channel_name       VARCHAR(60)  NOT NULL,
    sub_channel_name   VARCHAR(60)  NOT NULL,
    channel_group      VARCHAR(20)  NOT NULL,
    is_active          BOOLEAN      NOT NULL,
    is_confirmed       BOOLEAN      NOT NULL,
    is_unknown_member  BOOLEAN      NOT NULL DEFAULT FALSE
);

-- ---------------------------------------------------------------------------
-- Partner (counterparty). One row per name per role.
-- ---------------------------------------------------------------------------
CREATE TABLE core.dim_partner (
    partner_key            INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_name           VARCHAR(200) NOT NULL,
    partner_role           VARCHAR(10)  NOT NULL CHECK (partner_role IN ('CUSTOMER','SUPPLIER','UNKNOWN')),
    partner_type           VARCHAR(30)  NOT NULL,
    partner_group          VARCHAR(100),
    is_internal            BOOLEAN      NOT NULL,
    is_related_party       BOOLEAN      NOT NULL,
    is_sale_or_return      BOOLEAN      NOT NULL,
    classification_method  VARCHAR(15)  NOT NULL CHECK (classification_method IN ('LISTED','DEFAULT_RULE','UNKNOWN')),
    is_confirmed           BOOLEAN      NOT NULL,
    is_unknown_member      BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_dim_partner UNIQUE (partner_name, partner_role)
);

